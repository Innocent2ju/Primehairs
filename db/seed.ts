import { loadEnvConfig } from "@next/env";
loadEnvConfig(process.cwd());

import { db } from "../lib/db";
import { categories, products, productImages, stocks } from "./schema";
import { wigs } from "../lib/constants";

function slugify(text: string) {
  return text
    .toLowerCase()
    .trim()
    .replace(/[^\w\s-]/g, "")
    .replace(/[\s_-]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

async function seed() {
  console.log("🌱 Starting database seeding...");

  // 1. Clean existing records (in reverse FK order)
  console.log("Cleaning old catalog records...");
  await db.delete(stocks);
  await db.delete(productImages);
  await db.delete(products);
  await db.delete(categories);

  // 2. Extract and insert unique categories
  const categoryNames = Array.from(new Set(wigs.map((w) => w.category))).sort();
  console.log(`Inserting ${categoryNames.length} categories...`);

  const categoryMap = new Map<string, number>();

  for (const name of categoryNames) {
    const slug = slugify(name);
    const [inserted] = await db
      .insert(categories)
      .values({
        name,
        slug,
        description: `Premium collection of ${name.toLowerCase()} wigs and bundles.`,
      })
      .returning({ id: categories.id, name: categories.name });

    categoryMap.set(inserted.name, inserted.id);
  }

  // 3. Insert products, product_images, and stocks
  console.log(`Inserting ${wigs.length} products with stock and images...`);

  const baseTime = Date.now();

  for (let index = 0; index < wigs.length; index++) {
    const wig = wigs[index];
    const categoryId = categoryMap.get(wig.category);
    if (!categoryId) {
      throw new Error(`Category ${wig.category} not found in categoryMap`);
    }

    // Stagger created_at so products with higher index are newer
    // (e.g. Natural Afro Textured Wig is newest, Brazilian Body Wave is oldest)
    const createdAt = new Date(baseTime - (wigs.length - index) * 3600 * 1000 * 24);

    const [product] = await db
      .insert(products)
      .values({
        name: wig.name,
        slug: wig.slug,
        description: wig.description,
        price: wig.price.toFixed(2),
        material: "100% Virgin Human Hair",
        categoryId,
        createdAt,
        updatedAt: createdAt,
      })
      .returning({ id: products.id });

    // Primary image
    await db.insert(productImages).values({
      productId: product.id,
      url: wig.image,
      altText: `${wig.name} - Front View`,
      isPrimary: true,
      displayOrder: 0,
      createdAt,
    });

    // Provide a secondary image for selected products to demonstrate multiple images
    if (index % 2 === 0) {
      await db.insert(productImages).values({
        productId: product.id,
        url: "https://images.unsplash.com/photo-1560066984-138dadb4c035?w=600&q=80",
        altText: `${wig.name} - Detailed Texture Close-up`,
        isPrimary: false,
        displayOrder: 1,
        createdAt,
      });
    }

    // Insert stock (quantity + lowStockThreshold; status is generated by PostgreSQL)
    await db.insert(stocks).values({
      productId: product.id,
      quantity: wig.stock,
      lowStockThreshold: 5,
    });
  }

  console.log("✅ Database seeded successfully!");
  process.exit(0);
}

seed().catch((err) => {
  console.error("❌ Seeding failed:", err);
  process.exit(1);
});
